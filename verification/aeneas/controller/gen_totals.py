#!/usr/bin/env python3
"""Generates src/risk/totals.rs from contracts/controller/src/risk/totals.rs.

Aeneas cannot translate `fn` pointer types with a higher-ranked lifetime
(`fn(&Env, Ray, Ray, Wad) -> Wad`, "arrow types with locally quantified
regions") nor the coercion of `position_value`/`position_value_ceil` to such
a pointer. The production file is copied verbatim except for four exact
substitutions that replace the pointer by an enum naming the same two
functions, plus the enum itself (appended). Every substitution must match
exactly once, so a production edit near these lines fails the extraction
instead of silently changing the copy. See ../docs/extraction.md.
"""
import pathlib, sys

here = pathlib.Path(__file__).resolve().parent
src = here / "../../../contracts/controller/src/risk/totals.rs"
dst = here / "src/risk/totals.rs"
text = src.read_text()

SUBS = [
    ("    value: fn(&Env, Ray, Ray, Wad) -> Wad,\n", "    value: DebtValue,\n"),
    ("            value(\n                env,\n", "            value.apply(\n                env,\n"),
    ("sum_debt_usd_loaded(env, cache, borrow_positions, position_value)\n",
     "sum_debt_usd_loaded(env, cache, borrow_positions, DebtValue::HalfUp)\n"),
    ("sum_debt_usd_loaded(env, cache, borrow_positions, position_value_ceil);\n",
     "sum_debt_usd_loaded(env, cache, borrow_positions, DebtValue::Ceil);\n"),
]
for old, new in SUBS:
    n = text.count(old)
    if n != 1:
        sys.exit(f"gen_totals.py: expected exactly one occurrence of {old!r}, found {n}")
    text = text.replace(old, new)

header = (
    "// GENERATED by controller/gen_totals.py from\n"
    "// contracts/controller/src/risk/totals.rs: verbatim except that the `fn`\n"
    "// pointer argument of `sum_debt_usd_loaded` is replaced by `DebtValue`.\n"
    "// Do not edit.\n\n"
)
footer = '''
/// Verification only (not in production): the two functions production
/// passes to `sum_debt_usd_loaded` as a `fn` pointer, named by an enum so
/// that Aeneas can translate the call. `apply` calls exactly that function.
#[derive(Clone, Copy)]
pub(crate) enum DebtValue {
    /// `position_value` (half-up), passed by `sum_debt_usd`.
    HalfUp,
    /// `position_value_ceil`, passed by `calculate_account_risk_totals_body`.
    Ceil,
}

impl DebtValue {
    fn apply(self, env: &Env, scaled: Ray, index: Ray, price: Wad) -> Wad {
        match self {
            DebtValue::HalfUp => position_value(env, scaled, index, price),
            DebtValue::Ceil => position_value_ceil(env, scaled, index, price),
        }
    }
}
'''
dst.write_text(header + text + footer)
