#!/usr/bin/env python3
"""Regenerates the proof files that are copies of RatesAeneas proofs.

Each extraction crate generates its own copy of the `common` math, under its
own namespace, so a proof about that math has to exist once per library
(WRITING-PROOFS.md, last section). The files listed here are the RatesAeneas
proof with only the names of the library, the crate and the shim changed.
They are written by this script, never by hand: edit the RatesAeneas
original and re-run.

Usage: ./sync_copies.py           rewrite the copies
       ./sync_copies.py --check   exit status 1 if a copy is out of date (run.sh)
"""
import pathlib
import sys

LEAN = pathlib.Path(__file__).resolve().parent / "lean"

# library -> (crate namespace, shim namespace, further renames, files)
COPIES = {
    "PoolAeneas": (
        "pool_aeneas",
        "aeneas_pool_shim",
        # The pool crate mounts `common/src/constants` at `crate::constants`.
        [("constants.production.", "constants.")],
        ["MulDiv", "Host", "Scaling", "FloorCeilCore", "FloorCeilRescale", "FloorCeilRoundTrip",
         "HalfUp", "HalfUpDivInt"],
    ),
    "ControllerAeneas": (
        "controller_aeneas",
        "aeneas_soroban_shim",
        [],
        ["MulDiv", "Host", "FloorCeilRescale", "HalfUp", "HalfUpDivInt"],
    ),
}


def expected(lib: str, name: str) -> str:
    crate, shim, renames, _ = COPIES[lib]
    text = (LEAN / "RatesAeneas/Proofs" / f"{name}.lean").read_text()
    for old, new in [("RatesAeneas", lib), ("rates_aeneas", crate), ("aeneas_soroban_shim", shim)] + renames:
        text = text.replace(old, new)
    header = (
        f"-- GENERATED by ../sync_copies.py from RatesAeneas/Proofs/{name}.lean (library, crate and\n"
        "-- shim names changed). Do not edit: change the original and re-run the script.\n"
    )
    return header + text


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for lib, (_, _, _, files) in COPIES.items():
        for name in files:
            path = LEAN / lib / "Proofs" / f"{name}.lean"
            want = expected(lib, name)
            if path.read_text() != want:
                stale.append(str(path.relative_to(LEAN.parent)))
                if not check:
                    path.write_text(want)
    total = sum(len(v[3]) for v in COPIES.values())
    if check and stale:
        for p in stale:
            print(f"sync_copies: {p} differs from its RatesAeneas original", file=sys.stderr)
        print("sync_copies: run ./sync_copies.py and rebuild", file=sys.stderr)
        return 1
    print(f"sync_copies: {total} copies, {len(stale)} {'out of date' if check else 'rewritten'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
